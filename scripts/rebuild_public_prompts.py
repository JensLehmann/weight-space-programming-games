"""Restore the full writer prompts of the public games from the released prompts and the official game files.

The released prompts (artifacts/public/<game>/prompts/{w,p,fa}.md) carry a placeholder instead of the
redacted official game source; everything else, including the game section's text and its `arcengine`
excerpts, is verbatim. For each game this script regenerates the redacted game source from the
official game file with the released redaction configs (wsp.redact_public.redact_source, the step of
public_section / scripts/build_sections_public.py that produces it), checks it against hashes.json,
puts it in place of the placeholder, and checks the reassembled game section against the section hash
and every reassembled prompt against the prompt hash frozen before any writer call
(manifests/rev2/freeze_public.json for w and p, freeze_fa.json for fa; for official.ka59,
manifests/rev2/freeze_public_ka59.json for all three and the section).

Needs `arcengine` installed (wsp.redact_public imports it) and the official game files, either from the
game package's cache as for evaluation (arc3_games.sources.source_root("official",
cache_dir=$ARC3_GAMES_CACHE_DIR)) or from --official-root, a directory with <id>/<version>/<id>.py as
published. Each game file is checked against env.source_sha256 in
manifests/rev2/queries_official.<id>.json first. The level split comes from the same manifests, so
neither the public-game survey nor the game package is needed with --official-root.

Usage: rebuild_public_prompts.py [--games ls20,ft09,...|all] [--official-root DIR] [--out DIR]
  --out  also write the full prompts to DIR/<game>/{w,p,fa}.md (default: check only)
Exit status 0 iff every reassembled prompt matches its frozen hash.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

ART = REPO / "artifacts" / "public"
ARMS = ("w", "p", "fa")


def frozen_prompts() -> dict[tuple[str, str], str]:
    """(game, w|p|fa) -> prompt SHA-256, and (game, "section") -> game-section SHA-256, as recorded in the
    freeze manifests before any writer call (freeze_public.json and freeze_fa.json; for official.ka59,
    all three prompts and the section in freeze_public_ka59.json)."""
    pub = json.loads((REPO / "manifests/rev2/freeze_public.json").read_text())["families"]
    fa = json.loads((REPO / "manifests/rev2/freeze_fa.json").read_text())["families"]
    out = {}
    for g, rec in pub.items():
        out[(g, "w")], out[(g, "p")] = rec["prompts"]["weights"], rec["prompts"]["python"]
        out[(g, "section")] = rec["section"]
    for g, rec in fa.items():
        if g.startswith("official."):
            out[(g, "fa")] = rec["prompt"]["sha256"]
    for p in sorted((REPO / "manifests/rev2").glob("freeze_public_*.json")):   # single-game additions
        rec = json.loads(p.read_text())
        g = rec["family"]
        if any(k[0] == g for k in out):
            raise ValueError(f"{p.name}: {g} is already frozen in freeze_public.json / freeze_fa.json")
        out[(g, "w")], out[(g, "p")] = rec["prompts"]["weights"]["sha256"], rec["prompts"]["python"]["sha256"]
        out[(g, "fa")], out[(g, "section")] = rec["prompts"]["freearch"]["sha256"], rec["section"]
    return out


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def placeholder(game: str, sha: str) -> str:
    gid = game.split(".", 1)[1]
    return (f"[GAME SOURCE NOT INCLUDED: the redacted (mechanics-only) source of the official game file `{gid}.py` "
            f"of {game}, generated by scripts/build_sections_public.py (wsp.redact_public.public_section); "
            f"restore it with scripts/rebuild_public_prompts.py; sha256 {sha}]")


def section_of(prompt: str) -> str:
    """The game section: between the title paragraph and the episode rules (wsp.prompts.build_prompt_v2)."""
    from wsp.prompts import episode_rules
    return prompt[prompt.index("\n\n") + 2: prompt.index("\n\n" + episode_rules())]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--games", default="all")
    ap.add_argument("--official-root", default=None)
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    import wsp.redact_public as R
    from wsp import public
    if a.official_root:
        root = Path(a.official_root).resolve()
        R.official_root = lambda: root
    else:
        R.CACHE = public.cache_dir()            # the cache the evaluation reads ($ARC3_GAMES_CACHE_DIR)
    frozen = frozen_prompts()
    games = (sorted(p.name for p in ART.glob("official.*")) if a.games == "all"
             else [g if g.startswith("official.") else f"official.{g}" for g in a.games.split(",")])
    failed = []
    for game in games:
        gid = game.split(".", 1)[1]
        man = json.loads((REPO / "manifests" / "rev2" / f"queries_{game}.json").read_text())
        assert R.n_levels(gid) == int(man["n_levels"])   # level split: released routes and frozen manifest agree
        if R.held_levels(gid) != sorted(man["held_out_levels"]):
            failed.append(f"{game}: held-out levels differ from the query manifest")
            continue
        src = R.source_path(gid)
        if hashlib.sha256(src.read_bytes()).hexdigest() != man["env"]["source_sha256"]:
            failed.append(f"{game}: {src.name} does not match env.source_sha256 of the query manifest")
            continue
        hx = json.loads((ART / game / "prompts" / "hashes.json").read_text())
        red, _ = R.redact_source(gid)
        block = f"```python\n{red}```"                  # as in wsp.redact_public.public_section
        if sha256_text(block) != hx["game_source_sha256"]:
            failed.append(f"{game}: regenerated game source does not match hashes.json")
            continue
        ph = placeholder(game, hx["game_source_sha256"])
        for arm in ARMS:
            text = (ART / game / "prompts" / f"{arm}.md").read_text(encoding="utf-8")
            if text.count(ph) != 1:
                failed.append(f"{game}/{arm}: placeholder not found exactly once")
                continue
            full = text.replace(ph, block)
            h = sha256_text(full)
            sec_ok = sha256_text(section_of(full)) == hx["section_sha256"] == frozen[(game, "section")]
            ok = sec_ok and h == hx["prompts"][arm]["sha256"] == frozen[(game, arm)]
            print(f"{game} {arm}: section {'ok' if sec_ok else 'MISMATCH'}, prompt sha256 {h} "
                  f"{'matches the frozen hash' if ok else 'MISMATCH'}", flush=True)
            if not ok:
                failed.append(f"{game}/{arm}: reassembled prompt does not match the frozen hashes")
            elif a.out:
                dst = Path(a.out) / game / f"{arm}.md"
                dst.parent.mkdir(parents=True, exist_ok=True)
                dst.write_text(full, encoding="utf-8")
    if failed:
        print("FAILED:\n  " + "\n  ".join(failed), file=sys.stderr)
        return 1
    print(f"{len(games)} games, {len(games) * len(ARMS)} prompts: all match their frozen hashes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
