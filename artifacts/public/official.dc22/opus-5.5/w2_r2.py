import numpy as np

def build():
    S = {"W1": (32, 19, 5, 5), "b1": (32,), "W2": (32, 32, 3, 3), "b2": (32,),
         "W3": (32, 96), "b3": (32,), "Wh": (16, 16, 3, 3), "Uh": (16, 32),
         "bh": (16,), "Wz": (128, 96), "bz": (128,), "Wm": (64, 64),
         "Wmz": (64, 128), "Wma": (64, 8), "bm": (64,), "Wo": (8, 192),
         "bo": (8,), "Wc": (1, 48), "bc": (1,)}
    p = {k: np.zeros(v, np.float64) for k, v in S.items()}
    W1, b1, W2, b2 = p["W1"], p["b1"], p["W2"], p["b2"]
    walkc = [1, 2, 6, 7, 8, 9, 11, 12, 13, 14, 15]
    for c in walkc:
        W1[0, c, 2, 2] = 1.0
        W1[1, c, 2, 2] = 1.0
        W1[2, c, 2, 2] = 1.0
    W1[1, 4, 2, 1] = 1.0; W1[1, 4, 2, 3] = 1.0; b1[1] = -2.0
    W1[2, 4, 1, 2] = 1.0; W1[2, 4, 3, 2] = 1.0; b1[2] = -2.0
    W1[3, 5, :, :] = -10.0
    W1[3, 11, 2, 2] += 2.0
    b1[3] = -1.0
    W1[4, 5, :, :] = 1.0
    W1[5, 5, :, :] = 1.0; b1[5] = -1.0
    pri = {8: 5.0, 9: 4.8, 6: 3.0, 15: 2.5, 11: 1.0, 10: 1.0, 2: 0.5, 12: 0.5}
    for c, w in pri.items():
        W1[6, c, 2, 2] = w
    dirs = [(0, -1), (0, 1), (-1, 0), (1, 0)]
    for k, (dx, dy) in enumerate(dirs):
        W1[7 + k, 14, 2 - 2 * dy, 2 - 2 * dx] = 1.0
    W2[0, 0, 1, 1] = 1.0; W2[0, 1, 1, 1] = -2.0; W2[0, 2, 1, 1] = -2.0
    W2[1, 3, 1, 1] = 1.0
    W2[2, 6, 1, 1] = 1.0; W2[2, 4, 1, 1] = 10.0; W2[2, 5, 1, 1] = -10.0; b2[2] = -10.0
    for k in range(4):
        W2[3 + k, 7 + k, 1, 1] = 1.0
    for c in range(7):
        p["W3"][c, c] = 1.0
    BIG = 1e30
    Uh, bh, Wh = p["Uh"], p["bh"], p["Wh"]
    Uh[0, 0] = BIG; Uh[0, 1] = 1e25; bh[0] = -BIG
    for k in range(4):
        Uh[1 + k, 3 + k] = BIG
        bh[1 + k] = -BIG
        Wh[1 + k, 0, 1, 1] = 1.0
    for (i, j) in ((0, 1), (2, 1), (1, 0), (1, 2)):
        Wh[0, 0, i, j] = 0.25
    for k in range(1, 5):
        p["Wz"][k, k] = 1.0
        p["Wo"][k, k] = 1.0
    bo = p["bo"]
    bo[0] = bo[7] = -1000.0
    bo[6] = 1e-20
    p["Wc"][0, 2] = 1.0
    out = {}
    for k, shp in S.items():
        a = np.asarray(p[k], dtype=np.float32)
        assert a.shape == shp
        out[k] = a
    return out
