def _orbits():
    seen, orbs = set(), []
    for r in range(-2, 3):
        for c in range(-2, 3):
            if (r, c) == (0, 0) or (r, c) in seen:
                continue
            o, p = [], (r, c)
            for _ in range(4):
                if p not in o:
                    o.append(p)
                p = (p[1], -p[0])
            seen.update(o)
            orbs.append(o)
    return orbs


