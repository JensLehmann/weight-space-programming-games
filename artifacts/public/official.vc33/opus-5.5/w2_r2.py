    p["Wc"][0, 1] = 1e-20
    p["Wc"][0, 32 + 1] = 1.0
    p["Wc"][0, 32 + 3] = 1e30
    p["Wc"][0, 32 + 15] = 1e28
    p["Wc"][0, 32 + 12] = 1e37
    p["Wc"][0, 32 + 13] = 1e37
    return p
