    p["Wh"][14, 14, 0, 1] = 0.33
    p["Wh"][14, 14, 1, 1] = 0.33
    p["Wh"][14, 14, 2, 1] = 0.33
    # h15: unreachable buttons in gate levels, nearer boat = higher
