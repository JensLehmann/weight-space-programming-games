    p["W1"][9, 12, 2, 2] = 1.0
    # ---- f2 ----
    for c in range(3):
        p["W2"][c, c, 1, 1] = 1.0
    p["W2"][3, 0, 1, 1] = -1.0
    p["W2"][3, 1, 1, 1] = -1.0
    p["W2"][3, 2, 1, 1] = -2.0
