import numpy as np


def build():
    shapes = {
        "W1": (32, 19, 5, 5), "b1": (32,), "W2": (32, 32, 3, 3), "b2": (32,),
        "W3": (32, 96), "b3": (32,), "Wh": (16, 16, 3, 3), "Uh": (16, 32),
        "bh": (16,), "Wz": (128, 96), "bz": (128,), "Wm": (64, 64),
        "Wmz": (64, 128), "Wma": (64, 8), "bm": (64,), "Wo": (8, 192),
        "bo": (8,), "Wc": (1, 48), "bc": (1,),
    }
    p = {k: np.zeros(s, np.float32) for k, s in shapes.items()}

    fruit = [10, 6, 15, 11, 12, 8]
    for c in fruit:
        p["W1"][0, c, 2, 2] = 1.0
    p["W1"][0, 16, 2, 2] = 126.0; p["b1"][0] = -19.0
    p["W1"][1, 16, 2, 2] = 126.0; p["b1"][1] = -19.0
    p["W1"][2, 9, 2, 2] = 1.0
    p["W1"][2, 16, 2, 2] = 126.0; p["b1"][2] = -19.0
    p["W1"][3, 16, 2, 2] = -126.0; p["b1"][3] = 19.0
    p["W1"][4, 16, 2, 2] = 126.0; p["b1"][4] = -125.0
    p["W1"][5, 9, :, :] = 1.0; p["b1"][5] = -12.0

    p["W2"][0, 0, 1, 1] = 1.0; p["W2"][0, 1, 1, 1] = -1.0
    p["W2"][0, 5, 1, 1] = -3.0
    p["W2"][1, 2, 1, 1] = 1.0; p["W2"][1, 1, 1, 1] = -1.0
    p["W2"][2, 3, 1, 1] = 1.0; p["W2"][2, 4, 1, 1] = 1.0

    for i in range(3):
        p["W3"][i, i] = 1.0

    a_f = 0.07
    a_t = 0.11
    n = 41
    c0 = n // 2
    src = np.zeros((n, n)); src[c0, c0] = 1.0
    h = np.zeros((n, n))
    for _ in range(128):
        hp = np.pad(h, 1)
        s = np.zeros((n, n))
        for di in range(3):
            for dj in range(3):
                s += hp[di:di + n, dj:dj + n]
        h = np.maximum(a_f * s + src, 0.0)
    theta = float(h[c0, c0 + 6])

    M = 1e9
    p["Uh"][0, 0] = 1.0
    p["Uh"][1, 1] = 1.0
    p["Uh"][3, 2] = -M
    p["Wh"][0, 0, :, :] = a_f
    p["Wh"][1, 1, :, :] = a_t
    p["bh"][2] = 1.0
    p["Wh"][2, 0, 1, 1] = -1.0 / theta
    p["Wh"][3, 1, 1, 1] = 1.0
    p["Wh"][3, 2, 1, 1] = -M

    p["Wc"][0, 35] = 1.0
    p["bo"][6] = 1.0
    return {k: v.astype(np.float32) for k, v in p.items()}
